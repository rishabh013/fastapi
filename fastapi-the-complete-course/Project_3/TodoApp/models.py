from database import Base
from sqlalchemy import Column, Integer, String, Boolean, ForeignKey

'''We have created the two tables Users and Todos with their respective columns
In the users table we have details of users and
in the todos table we have details of todo items created by users
Each todo item is linked to a user through owner_id foreign key'''

class Users(Base):
    __tablename__ = 'users'

    id = Column(Integer, primary_key=True, index=True)
    email = Column(String, unique=True)
    username = Column(String, unique=True)
    first_name = Column(String)
    last_name = Column(String)
    hashed_password = Column(String)
    is_active = Column(Boolean, default=True)
    role = Column(String)


class Todos(Base):
    __tablename__ = 'todos'

    id = Column(Integer, primary_key=True, index=True)
    title = Column(String)
    description = Column(String)
    priority = Column(Integer)
    complete = Column(Boolean, default=False)
    owner_id = Column(Integer, ForeignKey("users.id"))
